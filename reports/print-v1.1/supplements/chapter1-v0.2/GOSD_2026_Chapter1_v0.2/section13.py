def tiny_network(f,x,y,mode):
    persons=[(x+35,y+20,'甲'),(x+35,y+83,'乙'),(x+35,y+146,'丙'),(x+35,y+209,'丁')]
    repos=[(x+232,y+42,'P'),(x+232,y+121,'Q'),(x+232,y+200,'R')]
    edges=[(0,0),(1,0),(1,1),(2,0),(2,2),(3,0),(3,1)]
    for a,b in edges:
        px,py,_=persons[a];rx,ry,_=repos[b];f.line(px+18,py,rx-23,ry,'soft',1.8)
    for px,py,n in persons:
        c='teal' if mode=='people' else 'soft';f.circle(px,py,18,c);f.text(px,py+7,n,20,'white',True,'middle',False)
    for rx,ry,n in repos:
        c='violet' if mode=='repo' else 'soft';f.rect(rx-22,ry-20,44,40,c);f.text(rx,ry+8,n,22,'white',True,'middle',False)

